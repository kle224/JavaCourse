package Section07;

public class Exercise01 {
	public static void run() {
		int number = 2;
		
		// This is a general demonstration of a switch statement
		
		switch (number) {
		case 1:
			System.out.println("You made the first place!");
			break;
		case 2:
			System.out.println("You made the second place!");
			break;
		case 3:
			System.out.println("You made the third place!");
			break;
		default:
			System.out.println("You performed at the big event!");
			break;
		}
	}
}
